/* Returns { mode: 'closed' | 'permalink' | 'perline', url?, lines? } — never drops a line.
   permalink: ALL lines have IDs → one combined /cart/<id>:<qty>,… link (one Shopify cart).
   perline:   some IDs missing → lines WITH IDs use /cart/add?id=<id>&quantity=<qty> (adds to the
              existing Shopify cart instead of starting a new one); lines WITHOUT IDs link to the product page.
              VERIFY once the store is live that /cart/add via GET accumulates into one cart. */
function checkoutPlan(items) {
items = items || cart;
if (!items.length) return { mode: 'empty' };
if (!STORE_LIVE) return { mode: 'closed' };
const ids = items.map(i => variantId(PRODUCTS[i.id].handle, i.color, i.size));
if (ids.every(Boolean)) return { mode: 'permalink', url: SHOP + '/cart/' + items.map((i, n) => ids[n] + ':' + i.qty).join(',') };
return { mode: 'perline', lines: items.map((i, n) => ({ line: i, hasId: !!ids[n], url: ids[n] ? SHOP + '/cart/add?id=' + encodeURIComponent(ids[n]) + '&quantity=' + i.qty : PRODUCTS[i.id].url })) };
}
